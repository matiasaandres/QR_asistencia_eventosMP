function titleCase(str) {
  return str.toLowerCase().split(' ').map(word => {
    if (word.length === 0) return '';
    return word.charAt(0).toUpperCase() + word.slice(1);
  }).join(' ');
}

function normalizeCourse(c) {
  if (!c || c === 'RET' || c.toUpperCase().includes('RET')) return 'Retirado';
  let cleaned = c.trim().toUpperCase();
  // Map Prebasica
  if (cleaned === 'K-A' || cleaned === 'KINDER A') return 'Kínder A';
  if (cleaned === 'K-B' || cleaned === 'KINDER B') return 'Kínder B';
  if (cleaned === 'PK-A' || cleaned === 'PREKINDER A') return 'Prekínder A';
  if (cleaned === 'PK-B' || cleaned === 'PREKINDER B') return 'Prekínder B';
  if (cleaned === 'PK-C' || cleaned === 'PREKINDER C') return 'Prekínder C';
  if (cleaned === 'MM-A' || cleaned === 'MEDIO MAYOR A') return 'Medio Mayor A';
  if (cleaned === 'MM-B' || cleaned === 'MEDIO MAYOR B') return 'Medio Mayor B';
  if (cleaned === 'MM-C' || cleaned === 'MEDIO MAYOR C') return 'Medio Mayor C';
  
  // Map Basica
  if (cleaned.startsWith('6')) return '6° Básico A';
  if (cleaned.startsWith('5')) return '5° Básico A';
  if (cleaned.startsWith('4')) return '4° Básico A';
  if (cleaned.startsWith('3')) return '3° Básico A';
  if (cleaned.startsWith('2')) return '2° Básico A';
  if (cleaned.startsWith('1')) return '1° Básico A';
  return cleaned;
}

function normalizeRutDisplay(value) {
  const cleaned = String(value || '').toUpperCase().replace(/[^0-9K]/g, '');
  if (cleaned.length < 8) return '';
  const body = cleaned.slice(0, -1);
  const verifier = cleaned.slice(-1);
  return `${Number(body).toLocaleString('es-CL')}-${verifier}`;
}

