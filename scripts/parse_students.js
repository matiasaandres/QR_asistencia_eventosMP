function titleCase(str) {
  return str.toLowerCase().split(' ').map(word => {
    if (word.length === 0) return '';
    return word.charAt(0).toUpperCase() + word.slice(1);
  }).join(' ');
}

const students = rawList.map((line, idx) => {
  const parts = line.split('\t').map(p => p.trim()).filter(Boolean);
  const nameRaw = parts[0]
    .replace(/\u00A0/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  
  // Last part is the course or RET
  let courseRaw = parts[parts.length - 1].trim();
  let rut = '';
  // find RUT if available (contains dot and dash)
  for (const part of parts) {
    if (part.includes('-') && (part.includes('.') || part.length >= 8)) {
      rut = part;
    }
  }

  const isRet = courseRaw === 'RET' || courseRaw.toUpperCase().includes('RET');
  
  // Standardize course label
  let course = courseRaw;
  if (isRet) {
    course = 'Retirado';
  } else {
    // Standardize 1°A, 2°A, 3°A, 4°A, 5°A, 6°A
    course = course.replace('ª', '°').replace(' A', '°A').replace(' 1 A', '1°A').replace('1 A', '1°A');
    if (!course.includes('°') && /^[1-6]/.test(course)) {
      course = course[0] + '°A';
    }
  }

  return {
    id: 'MP-2026-' + String(idx + 1).padStart(3, '0'),
    name: titleCase(nameRaw),
    rawName: nameRaw,
    course: course,
    maxCapacity: isRet ? 0 : 5,
    enteredCount: 0,
    status: isRet ? 'RETIRADO' : 'PENDIENTE'
  };
});

